// Department.js - the one model for all 9 department pages (Faculty > Departments).
// The starting content of every department is in the list below (it used to be data/departments.js), so there is no separate data file.
// Department.seed() adds a department from this list only when it is not in the database yet, so edits made in the admin are never overwritten.
//
// One document per department:
//   slug, order, shortName   link name (/departments/<slug>), position in the list, name in the department switcher
//   banner                   the wide picture at the top of the page
//   title, titleLine2, lead  the title block (titleLine2 = optional second line of the title)
//   facts                    the quick facts under the title (icons are fixed, they are not edited)
//   image, imageAlt          the framed department picture
//   collage                  the 3 About pictures [large, top-right, bottom-right] - always exactly 3
//   tiles                    the 3 small number tiles in the About card - always exactly 3
//   about                    the About sections. view: "text" paragraphs only, "chips" items as chips, "list" items as a tick list.
//                            wide = full-width card. The FIRST section is the card beside the collage.
//   staff                    one row per person (empty fields are not shown on the page)
//   highlights               the 4 picture cards at the bottom - always exactly 4
const mongoose = require("mongoose");

const sub = (fields) => new mongoose.Schema(fields, { _id: false });

const DepartmentSchema = new mongoose.Schema(
  {
    slug: { type: String, required: true, unique: true, trim: true },
    order: { type: Number, default: 0 },
    shortName: { type: String, default: "" },
    labels: sub({
      eyebrow: { type: String, default: "" },
      bannerTagLeft: { type: String, default: "" },
      bannerTagRight: { type: String, default: "" },
      breadcrumb: { type: String, default: "" },
      switcherLabel: { type: String, default: "" },
      aboutTab: { type: String, default: "" },
      staffTab: { type: String, default: "" },
      searchAbout: { type: String, default: "" },
      searchStaff: { type: String, default: "" },
      qualificationLabel: { type: String, default: "" },
      interestLabel: { type: String, default: "" },
      highlightsEyebrow: { type: String, default: "" },
      highlightsTitle: { type: String, default: "" },
      highlightsTitleHighlight: { type: String, default: "" },
      photoPlaceholder: { type: String, default: "" },
    }),
    banner: { type: String, default: "" },    title: { type: String, default: "" },
    titleLine2: { type: String, default: "" },
    lead: { type: String, default: "" },
    facts: [sub({ text: { type: String, default: "" } })],
    image: { type: String, default: "" },
    imageAlt: { type: String, default: "" },
    collage: [sub({ src: { type: String, default: "" }, alt: { type: String, default: "" } })],
    tiles: [sub({ value: { type: String, default: "" }, label: { type: String, default: "" } })],
    about: [
      sub({
        id: { type: String, default: "" },
        title: { type: String, default: "" },
        view: { type: String, enum: ["text", "chips", "list"], default: "text" },
        wide: { type: Boolean, default: false },
        paragraphs: [String],
        items: [String],
        closing: [String],
      }),
    ],
    staff: [
      sub({
        name: { type: String, default: "" },
        role: { type: String, default: "" },
        photo: { type: String, default: "" },
        qualification: { type: String, default: "" },
        interest: { type: String, default: "" },
        email: { type: String, default: "" },
      }),
    ],
    highlights: [
      sub({
        value: { type: String, default: "" },
        label: { type: String, default: "" },
        image: { type: String, default: "" },
        text: { type: String, default: "" },
      }),
    ],
  },
  { timestamps: true }
);

