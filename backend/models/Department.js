// adds the departments that are not in the database yet (edited ones are left alone)
DepartmentSchema.statics.seed = async function () {
  const have = (await this.find({}, "slug").lean()).map((row) => row.slug);
  const missing = departments.filter((row) => !have.includes(row.slug));
  if (missing.length) await this.insertMany(missing);
  for (const row of departments) {
    await this.updateOne(
      { slug: row.slug, labels: { $exists: false } },
      { $set: { labels: row.labels } }
    );
  }
};

const Department = mongoose.model("Department", DepartmentSchema);

